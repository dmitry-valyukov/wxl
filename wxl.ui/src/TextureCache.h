#pragma once

#include <wxl/Microsoft.UI.Composition.h>

#include <filesystem>
#include <memory>

#include "Operation.h"

// wxl::TextureCache -- картинки и текстуры в видеопамяти, загружаемые
// асинхронно и удерживаемые по пути файла.
//
// Стоит на Win2D (Microsoft.Graphics.Canvas): декод и заливку в видеопамять
// делает CanvasBitmap.LoadAsync -- на своих потоках, не на нашем, -- а
// рисование готового битмапа в композиторную поверхность -- CanvasComposition
// поверх нашего же Microsoft.UI-композитора. Так задник, обложка и (позже)
// буквица оказываются текстурой в видеопамяти, которую композитор двигает и
// растягивает как любой визуал. Страница книги при этом остаётся на сыром
// Direct2D через DrawingSurface -- это её другой путь.
//
// Кэш -- одна поверхность на путь: один и тот же файл декодится и заливается
// раз, а дальше отдаётся готовым.
//
// Асинхронность -- та же, что у любой операции платформы в обёртках (Operation.h):
// getAsync() отдаёт async::task, который корутина wxl co_await-ит. Пока картинки
// нет в кэше, это задача над CanvasBitmap.LoadAsync в форме с токеном: завершение
// приходит на поток пула WinRT и только кладётся в очередь UI-потока, а там -- уже
// на UI-потоке -- из битмапа делается поверхность, рисуется, кэшируется и
// отдаётся ждущему. Брошенная задача отменяет загрузку и ничего не будит; отмена
// токена -- тоже, и ожидание кончается отменой. Так winrt наружу не течёт, а
// возврат на UI-поток -- тот же, что у обёрток (impl/operation.h).
//
// Обёртка, не владелец видеопамяти: копия -- второй handle на тот же кэш; сам
// кэш живёт, пока жив любой его handle или незавершённый запрос к нему.

namespace wxl {

class TextureCache {
public:
    /// Кэш поверх этого композитора: в его поверхности рисуются текстуры, его
    /// же кистями они попадают на визуалы. Микрософт-UI-композитор -- тот
    /// самый, что несёт сцену окна.
    explicit TextureCache(Compositor const& compositor);
    ~TextureCache();

    TextureCache(TextureCache&&) noexcept;
    TextureCache& operator=(TextureCache&&) noexcept;
    TextureCache(TextureCache const&) = delete;
    TextureCache& operator=(TextureCache const&) = delete;

    /// Поверхность с картинкой из файла: из кэша, если уже грузили (задача
    /// готова сразу), иначе загрузкой в видеопамять под токеном `stop`. Его
    /// отмена просит платформу остановить загрузку и кончает ожидание
    /// async::operation_canceled_exception, как у всякой операции платформы с
    /// токеном; под отменённым токеном загрузка не начинается. Путь абсолютный.
    async::task<CompositionDrawingSurface> getAsync(std::filesystem::path const& image,
                                                    async::cancellation_token stop);

    /// Забыть всё: следующий getAsync грузит заново. Видеопамять освобождается,
    /// когда её перестают держать и кэш, и кисти на визуалах.
    void clear();

private:
    // shared: незавершённая загрузка держит его тоже, чтобы устройство и карта
    // пережили запрос, даже если сам кэш-обёртку выронили.
    struct Impl;
    std::shared_ptr<Impl> impl_;
};

}  // namespace wxl
