#pragma once

#include <wxl/Microsoft.UI.Composition.h>

#include <filesystem>

#include "Operation.h"

// wxl::TextureCache -- картинки и текстуры в видеопамяти, загружаемые
// асинхронно и удерживаемые по пути файла.
//
// Стоит на Win2D (Microsoft.Graphics.Canvas): декод и заливку в видеопамять
// делает CanvasBitmap.LoadAsync -- на своих потоках, не на нашем, -- а
// рисование готового битмапа в композиторную поверхность -- CanvasComposition
// поверх нашего же Microsoft.UI-композитора. Так задник, обложка и (позже)
// буквица оказываются текстурой в видеопамяти, которую композитор двигает и
// растягивает как любой визуал. Страница книги при этом остаётся на сыром
// Direct2D через DrawingSurface -- это её другой путь.
//
// Кэш -- одна поверхность на путь: один и тот же файл декодится и заливается
// раз, а дальше отдаётся готовым.
//
// Асинхронность -- та же, что у любой операции платформы в обёртках (Operation.h):
// getAsync() отдаёт async::task, который корутина wxl co_await-ит. Пока картинки
// нет в кэше, это задача над CanvasBitmap.LoadAsync в форме с токеном: завершение
// приходит на поток пула WinRT и только кладётся в очередь UI-потока, а там -- уже
// на UI-потоке -- из битмапа делается поверхность, рисуется, кэшируется и
// отдаётся ждущему. Брошенная задача отменяет загрузку и ничего не будит; отмена
// токена -- тоже, и ожидание кончается отменой. Так winrt наружу не течёт, а
// возврат на UI-поток -- тот же, что у обёрток (impl/operation.h).
//
// Устройство теряется (обновление драйвера, сброс GPU), и с ним -- пиксели всех
// поверхностей. Устройство Win2D у кэша своё, и адаптер ему выбирает Win2D --
// аппаратный по умолчанию, а не вышло -- WARP; устройство, через которое рисуют
// все DrawingSurface, wxl ищет сам -- первый адаптер, который его делает, WARP
// последним. Обычно это один адаптер, но не обязательно. Кэш следит за
// устройством wxl (заводит его с первой загрузкой), которое wxl на потерю
// заменяет: после замены кэш при следующем getAsync забывает всё и переходит на
// новое устройство Win2D, так что картинка грузится заново, а загрузка, которую
// замена застала, повторяется уже на новом. Поверхность, отданная прежде, пуста:
// кто её держит, слышит замену своим RenderingDeviceWatch -- на этом композиторе
// или любом другом, держатели зовутся все -- и просит картинку снова. Отказ
// Win2D, который его устройство подтверждает потерей, wxl не слышит: кэш сам
// просит ту же замену, а загрузка кончается DrawingSurface::DeviceLost. Устройство
// Win2D на другом адаптере, потерянное, пока ничего не грузится, не слышит никто
// до первой загрузки, которой оно откажет.
//
// Не копируется и не перемещается: пустого кэша не бывает. У кэша один владелец,
// и сам кэш живёт, пока жив он или незавершённый запрос, который держит его
// состояние.

namespace wxl {

class TextureCache : core::noncopyable {
public:
    /// Кэш поверх этого композитора: в его поверхности рисуются текстуры, его
    /// же кистями они попадают на визуалы. Микрософт-UI-композитор -- тот
    /// самый, что несёт сцену окна.
    explicit TextureCache(Compositor const& compositor);
    ~TextureCache();

    /// Поверхность с картинкой из файла: из кэша, если уже грузили (задача
    /// готова сразу), иначе загрузкой в видеопамять под токеном `token`. Его
    /// отмена просит платформу остановить загрузку и кончает ожидание
    /// async::operation_canceled_exception, как у всякой операции платформы с
    /// токеном; под отменённым токеном ничего не начинается и задача сразу
    /// кончается отменой -- даже картинка из кэша не отдаётся. Загрузка, которую
    /// оборвало потерянное устройство, кончается DrawingSurface::DeviceLost:
    /// просить снова -- когда позовут RenderingDeviceWatch. Путь абсолютный.
    async::task<CompositionDrawingSurface> getAsync(std::filesystem::path const& image,
                                                    async::cancellation_token token);

    /// Забыть всё: следующий getAsync грузит заново. Видеопамять освобождается,
    /// когда её перестают держать и кэш, и кисти на визуалах.
    void clear();

private:
    // Со счётчиком: незавершённая загрузка держит его тоже, чтобы устройство и
    // карта пережили запрос, даже если владелец кэша ушёл. Счётчик одного
    // потока: кэш и кадры загрузки трогает только UI-поток.
    struct Impl;
    core::intrusive_ptr<Impl> const impl_;
};

}  // namespace wxl
