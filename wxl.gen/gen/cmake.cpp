#include <format>
#include <ostream>
#include <print>

#include "wxl.gen.h"

import std;

// The generated directory's own CMakeLists.txt. It defines no target of
// its own: it is add_subdirectory()'d *after* the consuming target exists
// and only adds sources to it, so the generated tree stays a leaf of the
// build rather than a thing the rest of the build has to know about.
//
// AI note: headers are listed alongside the .cpp files on purpose --
// MSVC/Visual Studio shows them in the project tree, and CMake ignores
// them for compilation. Nothing here should ever be hand-edited; the file
// is rewritten on every generator run.

namespace gen {

void write_cmake_lists(Output const& out, Emitted const& emitted) {
    auto const path = out.dir / "CMakeLists.txt";
    auto file = open_output(path);

    std::print(file, R"(# Generated by winui-srcgen. Do not edit by hand.
#
# Not a target of its own: add_subdirectory() this directory *after* the
# `{}` target has been created, e.g.
#
#     add_library({} ...)
#     add_subdirectory(src/generated)
#
target_sources({} PRIVATE
)",
               out.cmake_target, out.cmake_target, out.cmake_target);

    for (auto&& name : emitted.files_of({})) {
        std::print(file, "    ${{CMAKE_CURRENT_SOURCE_DIR}}/{}\n", name);
    }

    std::print(file, ")\n");

    // Everything else a writer produced for a target of its own -- today
    // that is the schema's test, which has to be compiled by the surface
    // test rather than linked into the library. Guarded, because the
    // directory is add_subdirectory()'d by the library's CMakeLists and the
    // test target beside it may not have been created yet.
    for (auto&& target : emitted.targets()) {
        if (target.empty()) {
            continue;
        }

        std::print(file, R"(
if(TARGET {})
    target_sources({} PRIVATE
)",
                   target, target);
        for (auto&& name : emitted.files_of(target)) {
            std::print(file, "        ${{CMAKE_CURRENT_SOURCE_DIR}}/{}\n", name);
        }
        std::print(file, "    )\nelse()\n    message(FATAL_ERROR\n        \"{} is generated for "
                         "the target {}, which does not exist yet -- create it before \"\n"
                         "        \"add_subdirectory() of this directory.\")\nendif()\n",
                   emitted.files_of(target).front(), target);
    }

    std::print(file, R"(

# The generated sources include each other by bare name ("Button.h",
# "PropertyKey.h"), and the hand-written sources one level up expect the
# same, so this directory has to be on the target's include path.
target_include_directories({} PUBLIC ${{CMAKE_CURRENT_SOURCE_DIR}})
)",
               out.cmake_target);

    std::print("wrote {} ({} sources)\n", path.string(), emitted.files().size());
}

}  // namespace gen
